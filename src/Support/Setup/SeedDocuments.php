<?php

namespace Plugins\G7\Light\Wiki\Support\Setup;

/**
 * 세트 설치가 만드는 시드 문서 3건 — 순수 정의 (DB·HTTP·설정 접근 없음).
 *
 * ## 순서
 *
 * 모든 문서 → 위키 문법 도움말 → 대문. 대문이 앞의 둘을 `[[…]]` 로 가리키므로 마지막에
 * 만든다. 링크 색(있음·없음)은 그릴 때 정해져 순서가 틀려도 결과는 같지만, 대문이 처음
 * 그려지는 순간 대상 문서가 이미 있으면 봇 캐시에 빨간 링크가 박힐 틈이 없다.
 *
 * ## 본문 규칙
 *
 * - `content_mode = html`. 평문 모드면 화면이 본문을 통째로 이스케이프하고 표기도 뽑지 않는다.
 * - 자리표시는 기존 대문 글들과 같이 `<p>` 한 줄에 둔다(스테이징 글 38·39 와 같은 모양).
 * - 검색창은 템플릿이 대문 위에 그리므로 본문에 넣지 않는다.
 * - `$t:` 모양의 글자를 쓰지 않는다 — 방문자 화면과 봇 SSR 이 본문 안의 그 모양을 번역으로 바꾼다.
 * - 문법 문서 본문({@see SYNTAX_BODY})은 **새로 만드는 시드에만** 들어간다. 이미 만들어진 문법
 *   문서는 바꾸지 않는다(시드는 세트 설치 때 한 번 만든다).
 */
final class SeedDocuments
{
    public const INDEX = 'index';

    public const SYNTAX = 'syntax';

    public const FRONT = 'front';

    /** 문서 제목 — 대문 본문의 링크와 글자가 같아야 한다 */
    public const TITLES = [
        self::INDEX => '모든 문서',
        self::SYNTAX => '위키 문법 도움말',
        self::FRONT => '대문',
    ];

    /**
     * "위키 문법 도움말" 본문.
     *
     * 예시 표기는 **모두 `<code>` 안**에 있다 — 코드 서식 안의 `[[…]]` 는 화면 치환도, 저장 때
     * 추출(분류·별칭·연표·역링크)도 하지 않으므로 글자 그대로 보이고 아무것도 등록되지 않는다.
     * 번역 토큰 모양(달러 기호 + t + 쌍점)은 어떤 형태로도 넣지 않는다 — 방문자 화면과 봇 화면이
     * 코드 안에서도 번역으로 바꾼다. nowdoc 이라 `$`·`\` 가 해석되지 않고 글자가 그대로 들어간다.
     */
    private const SYNTAX_BODY = <<<'HTML'
<p>이 문서는 이 위키에서 쓸 수 있는 표기를 모아 설명합니다. 표기는 문서 본문에만 적으며, 목록 화면이나 검색 결과에서는 글자 그대로 보입니다.</p>

<h2>문서 링크</h2>
<p>대괄호 두 개로 문서 이름을 감싸면 그 문서로 가는 링크가 됩니다.</p>
<ul>
<li><code>[[설치 방법]]</code> — 문서가 있으면 파란 링크, 없으면 빨간 링크가 됩니다. 빨간 링크를 누르면 그 제목이 채워진 작성 화면으로 갑니다.</li>
<li><code>[[설치 방법|설치하기]]</code> — 화면에 보이는 글자만 바꿉니다. 세로줄 뒤에 보여 줄 글자를 적습니다.</li>
</ul>
<p>제목은 앞뒤 공백과 대소문자를 가리지 않고 찾습니다. 실제 제목을 먼저 찾고, 없으면 별칭에서 찾습니다.</p>

<h2>분류와 별칭</h2>
<ul>
<li><code>[[분류:인물]]</code> — 이 문서를 "인물" 분류에 넣습니다. 본문에서는 사라지고 문서 맨 아래 분류 줄에 모입니다. 분류도 하나의 문서라서, 제목이 "분류:인물"인 문서를 만들면 그 분류에 속한 문서 목록이 자동으로 붙습니다.</li>
<li><code>[[별칭:G7]]</code> — 이 문서의 다른 이름을 정합니다. 다른 문서에서 <code>[[G7]]</code>이라고 적으면 이 문서로 연결됩니다. 본문에서는 사라지고 문서 아래 "다른 이름" 줄에 모입니다.</li>
</ul>

<h2>연표</h2>
<p><code>[[연표:2024.3|정식 출시]]</code>처럼 적으면 사건이 등록되고, 본문에는 설명 글자만 남습니다. 설명을 빼면 키가 그대로 보입니다.</p>
<p>키는 숫자와 점으로만 적습니다. 점으로 최대 네 칸까지 나눌 수 있고, 칸마다 12자리까지 됩니다. 앞에 빼기 부호를 붙이면 기원전처럼 쓸 수 있습니다. 형식이 맞지 않으면 등록되지 않고 글자 그대로 남습니다.</p>

<h2>자리표시</h2>
<p>우물 정 기호로 시작하는 표기는 그 자리에 목록을 그립니다. 세로줄 뒤에 숫자를 적으면 개수를 정할 수 있습니다.</p>
<ul>
<li><code>[[#최근수정]]</code> — 최근에 고친 문서 목록입니다. 기본 10개, 최대 50개.</li>
<li><code>[[#최근작성]]</code> — 최근에 만든 문서 목록입니다. 기본 5개, 최대 50개.</li>
<li><code>[[#랜덤]]</code> — 무작위 문서 하나로 가는 링크입니다. <code>[[#랜덤|4]]</code>처럼 2 이상을 적으면 서로 다른 문서 목록이 됩니다. 열 때마다 다시 뽑습니다.</li>
<li><code>[[#색인]]</code> — 첫 글자로 묶은 전체 문서 목록입니다. 세로줄 뒤 숫자로 열 수를 정하며 기본 3, 1에서 4까지입니다. 좁은 화면에서는 열이 줄어듭니다.</li>
<li><code>[[#둘러보기]]</code> — 왼쪽에 최근 수정, 오른쪽에 무작위 문서를 두 단으로 보여 줍니다. 각 단 제목을 누르면 목록 화면으로 갑니다. 단마다 기본 5개.</li>
<li><code>[[#분류|인물]]</code> — 그 분류에 속한 문서 목록입니다. 분류 이름을 반드시 적어야 합니다.</li>
<li><code>[[#연표]]</code> — 등록된 사건을 키 순서로 늘어놓습니다. <code>[[#연표|G7 역사]]</code>처럼 문서 이름을 적으면 그 문서와 그 문서를 가리키는 문서들의 사건만 모읍니다.</li>
</ul>
<p>문서 목록에서는 대문과 지금 보고 있는 문서가 빠집니다. 비밀글과 답글도 나오지 않습니다. 문서가 아주 많으면 일부만 보입니다.</p>

<h2>문서 아래에 자동으로 붙는 것</h2>
<p>따로 적지 않아도 문서 맨 아래에 다음이 붙습니다.</p>
<ul>
<li>이 분류에 속한 문서 — 분류 문서일 때만</li>
<li>다른 이름 — 별칭을 정했을 때</li>
<li>이 문서를 가리키는 문서 — 다른 문서가 이 문서를 링크했을 때</li>
<li>분류 — 이 문서가 속한 분류</li>
</ul>

<h2>표기를 글자 그대로 보여 주려면</h2>
<p>코드 서식 안에 적으면 링크나 목록으로 바뀌지 않고 글자 그대로 보입니다. 이 문서의 예시도 모두 코드 서식으로 적혀 있습니다.</p>

<h2>표기가 되지 않는 경우</h2>
<ul>
<li>대괄호가 닫히지 않았거나 이름이 비어 있을 때</li>
<li>표기 중간에 굵게나 색 같은 서식이 걸려 있을 때</li>
<li>표기가 여러 줄에 걸쳐 있을 때</li>
<li>알 수 없는 자리표시 이름일 때</li>
</ul>
<p>이런 경우에는 적은 그대로 화면에 보입니다.</p>
HTML;

    /**
     * 만들 순서대로 시드 정의.
     *
     * @return list<array{key: string, title: string, content: string, content_mode: string}>
     */
    public static function all(): array
    {
        $seeds = [];

        foreach (array_keys(self::TITLES) as $key) {
            $seeds[] = [
                'key' => $key,
                'title' => self::TITLES[$key],
                'content' => self::body($key),
                'content_mode' => 'html',
            ];
        }

        return $seeds;
    }

    /**
     * 시드 본문 HTML.
     */
    public static function body(string $key): string
    {
        return match ($key) {
            self::INDEX => '<p>[[#색인]]</p>',
            self::SYNTAX => self::SYNTAX_BODY,
            self::FRONT => '<p>이 위키에 오신 것을 환영합니다.</p>'
                .'<p>[[#둘러보기]]</p>'
                .'<p>[['.self::TITLES[self::INDEX].']] · [['.self::TITLES[self::SYNTAX].']]</p>',
            default => throw new \InvalidArgumentException("알 수 없는 시드: {$key}"),
        };
    }
}
